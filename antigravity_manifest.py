"""The Google Antigravity manifest of each published plugin, and the separate copy a plugin with Claude agents needs.

Every published plugin also loads in Antigravity through ``.antigravity-plugin/plugin.json``: a manifest Claude Code
ignores, generated by ``automate_publish.py`` from the same data the Claude marketplace uses (``metadata.json`` for the
version and description, the category in ``install.config.json``, and the license or keywords the plugin's own Claude
manifest declares) — never written by hand. ``build_marketplace.py --check`` fails when one is missing or stale.

Antigravity scans a plugin's ``agents/`` folder and rejects an agent whose ``model`` is not one of its own
(``ANTIGRAVITY_MODELS``). A plugin whose published folder holds Claude agents there therefore keeps its Claude folder
exactly as Claude Code loads it, with no Antigravity manifest, and gets a generated copy for Antigravity under
``published-antigravity/<category>/<plugin>/``: the same files without ``agents/``, plus the manifest.

This module names no plugin and imports nothing from the repository's scripts.
"""

from __future__ import annotations

import json
import pathlib
import re
import shutil
import typing

#: The manifest Antigravity reads first in a folder shared with other tools; Claude Code ignores it.
MANIFEST = pathlib.Path(".antigravity-plugin") / "plugin.json"
SCHEMA = "https://antigravity.google/schemas/v1/plugin.json"
#: The repository's own coordinates: the homepage and the source repository of every plugin.
REPOSITORY = "https://github.com/pablolok/claude-skills"
#: The generated tree that holds the Antigravity copy of each plugin with Claude agents, beside ``published/``.
TREE = "published-antigravity"
#: The folder of subagents both tools scan at a plugin's root.
AGENTS = "agents"
#: The subagent models Antigravity accepts; any other (opus, sonnet, fable, none) makes the agent a Claude agent.
ANTIGRAVITY_MODELS = frozenset({"inherit", "flash", "pro", "flash_lite"})
#: A plugin's own Claude manifest (a mod's), and the fields of it the Antigravity manifest carries over when declared.
CLAUDE_MANIFEST = pathlib.Path(".claude-plugin") / "plugin.json"
CARRIED_FIELDS = ("license", "keywords")
METADATA = "metadata.json"
SKILL = "SKILL.md"
BUNDLE = "bundle"

_FENCE = "---"
_MODEL_LINE = re.compile(r"model:[ \t]*(.*?)[ \t]*$")


def display_name(name: str) -> str:
    """The plugin's name as words: ``savvy-flow`` reads ``Savvy Flow``."""
    return " ".join(part.capitalize() for part in name.split("-"))


def build(
    name: str,
    category: str,
    metadata: typing.Mapping[str, typing.Any],
    root_skill: bool,
    claude_manifest: typing.Optional[typing.Mapping[str, typing.Any]] = None,
) -> typing.Dict[str, typing.Any]:
    """The manifest of one plugin.

    ``root_skill`` is true for a plugin whose skill is its folder: only that one lists ``skills: ["./"]``. A bundle's
    nested ``skills/<skill>/`` are found without it, and a mod with no skill has none to list. No ``author``: the
    homepage and the repository name the source.
    """
    manifest: typing.Dict[str, typing.Any] = {
        "$schema": SCHEMA,
        "name": name,
        "displayName": display_name(name),
        "version": metadata["version"],
        "description": metadata["description"],
        "homepage": REPOSITORY,
        "repository": REPOSITORY,
        "category": category,
    }
    for field in CARRIED_FIELDS:
        if claude_manifest and field in claude_manifest:
            manifest[field] = claude_manifest[field]
    if root_skill:
        manifest["skills"] = ["./"]
    return manifest


def render(manifest: typing.Mapping[str, typing.Any]) -> str:
    """The file's text: stable formatting, LF, final newline."""
    return json.dumps(manifest, indent=2, ensure_ascii=False) + "\n"


def agent_model(text: str) -> typing.Optional[str]:
    """The ``model`` an agent file's frontmatter declares, unquoted, or None when it declares none."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != _FENCE:
        return None
    for line in lines[1:]:
        if line.strip() == _FENCE:
            return None
        match = _MODEL_LINE.fullmatch(line)
        if match is not None:
            return match.group(1).strip("'\"") or None
    return None


def has_claude_agents(folder: pathlib.Path) -> bool:
    """True when the plugin's ``agents/`` folder holds an agent Antigravity rejects (a model it does not run)."""
    agents = folder / AGENTS
    if not agents.is_dir():
        return False
    return any(
        agent_model(path.read_text(encoding="utf-8")) not in ANTIGRAVITY_MODELS
        for path in sorted(agents.glob("*.md"))
        if path.is_file()
    )


def _read_json(path: pathlib.Path) -> typing.Any:
    return json.loads(path.read_text(encoding="utf-8"))


def manifest_for(folder: pathlib.Path, category: str) -> typing.Dict[str, typing.Any]:
    """The manifest of the plugin published at ``folder``, from its own files."""
    metadata = _read_json(folder / METADATA)
    claude_path = folder / CLAUDE_MANIFEST
    claude_manifest = _read_json(claude_path) if claude_path.is_file() else None
    root_skill = metadata.get("kind") != BUNDLE and (folder / SKILL).is_file()
    return build(folder.name, category, metadata, root_skill, claude_manifest)


def copy_folder(folder: pathlib.Path, category: str, tree: pathlib.Path) -> pathlib.Path:
    """Where the Antigravity copy of the plugin published at ``folder`` lives."""
    return tree / category / folder.name


def _skip_root_agents(root: pathlib.Path) -> typing.Callable[[str, typing.List[str]], typing.Set[str]]:
    def skip(here: str, names: typing.List[str]) -> typing.Set[str]:
        return {AGENTS} if pathlib.Path(here) == root and AGENTS in names else set()
    return skip


def _write(path: pathlib.Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def publish(folder: pathlib.Path, category: str, tree: pathlib.Path) -> pathlib.Path:
    """Write the plugin's Antigravity manifest, and its separate copy when it has Claude agents; return where.

    Run on a freshly published folder. A copy left from a release that had Claude agents is removed.
    """
    text = render(manifest_for(folder, category))
    target = copy_folder(folder, category, tree)
    if target.exists():
        shutil.rmtree(target)
    if not has_claude_agents(folder):
        _write(folder / MANIFEST, text)
        return folder
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(folder, target, ignore=_skip_root_agents(folder))
    _write(target / MANIFEST, text)
    return target


def _files(folder: pathlib.Path) -> typing.Dict[str, bytes]:
    return {
        path.relative_to(folder).as_posix(): path.read_bytes()
        for path in sorted(folder.rglob("*"))
        if path.is_file()
    }


def problems(folder: pathlib.Path, category: str, tree: pathlib.Path, root: pathlib.Path) -> typing.List[str]:
    """What keeps the plugin published at ``folder`` from loading in Antigravity as the publish would leave it.

    Paths in the messages are relative to ``root``; an empty list means the manifest (and the copy) are current.
    """
    def where(path: pathlib.Path) -> str:
        return path.relative_to(root).as_posix()

    expected = render(manifest_for(folder, category))
    target = copy_folder(folder, category, tree)
    found: typing.List[str] = []
    if not has_claude_agents(folder):
        manifest = folder / MANIFEST
        if not manifest.is_file():
            found.append(f"{where(manifest)} is missing")
        elif manifest.read_text(encoding="utf-8") != expected:
            found.append(f"{where(manifest)} is out of date")
        return found
    if (folder / MANIFEST).exists():
        found.append(f"{where(folder / MANIFEST)} must not exist: {folder.name} has Claude agents, "
                     f"its Antigravity manifest belongs on {where(target)}")
    manifest = target / MANIFEST
    if not manifest.is_file():
        found.append(f"{where(manifest)} is missing")
        return found
    if manifest.read_text(encoding="utf-8") != expected:
        found.append(f"{where(manifest)} is out of date")
    wanted = {rel: data for rel, data in _files(folder).items()
              if not rel.startswith(AGENTS + "/") and rel != MANIFEST.as_posix()}
    copied = {rel: data for rel, data in _files(target).items() if rel != MANIFEST.as_posix()}
    if copied != wanted:
        differing = sorted(rel for rel in set(wanted) | set(copied) if wanted.get(rel) != copied.get(rel))
        found.append(f"{where(target)} differs from {where(folder)} without {AGENTS}/: {', '.join(differing[:5])}")
    return found


def orphans(tree: pathlib.Path, expected: typing.Iterable[pathlib.Path], root: pathlib.Path) -> typing.List[str]:
    """Copies in the tree that no published plugin with Claude agents accounts for."""
    if not tree.is_dir():
        return []
    wanted = {path.resolve() for path in expected}
    return [
        f"{path.relative_to(root).as_posix()} has no published plugin with Claude agents behind it"
        for path in sorted(tree.glob("*/*"))
        if path.is_dir() and path.resolve() not in wanted
    ]
